<?php

/**
 * Build the moz-extensions library map with PHP's own tokenizer.
 *
 * `arc liberate` analyzes source files with XHPAST, which can not parse the
 * PHP 7.4 syntax this library uses. This builds and writes the same map that
 * `PhutilLibraryMapBuilder` would, in the same format.
 */
final class MozExtensionsLibraryMapBuilder extends Phobject {

  private $root;

  public function __construct($root) {
    $this->root = $root;
  }

  public function buildAndWriteMap() {
    $library_map = array(
      PhutilLibraryMapBuilder::LIBRARY_MAP_VERSION_KEY =>
        PhutilLibraryMapBuilder::LIBRARY_MAP_VERSION,
    ) + $this->buildMap();

    $version = PhutilLibraryMapBuilder::LIBRARY_MAP_VERSION;
    $exported_map = phutil_var_export($library_map);
    $at = '@';

    $source = <<<EOPHP
<?php

/**
 * This file is automatically generated. Use 'just liberate' to rebuild it.
 *
 * {$at}generated
 * {$at}phutil-library-version {$version}
 */
phutil_register_library_map({$exported_map});

EOPHP;

    Filesystem::writeFile($this->root.'/__phutil_library_map__.php', $source);
  }

  public function buildMap() {
    $library_map = array(
      'class' => array(),
      'function' => array(),
      'xmap' => array(),
    );

    foreach ($this->findSourceFiles() as $path) {
      $declarations = $this->findDeclarations(
        Filesystem::readFile($this->root.'/'.$path));

      foreach ($declarations['class'] as $class_name => $parents) {
        $library_map['class'][$class_name] = $path;
        if (count($parents) == 1) {
          $library_map['xmap'][$class_name] = head($parents);
        } else if ($parents) {
          $library_map['xmap'][$class_name] = $parents;
        }
      }

      foreach ($declarations['function'] as $function_name) {
        $library_map['function'][$function_name] = $path;
      }
    }

    foreach ($library_map as $type => $symbols) {
      ksort($symbols);
      $library_map[$type] = $symbols;
    }

    return $library_map;
  }

  /**
   * List the files `arc liberate` would analyze, relative to the root.
   */
  private function findSourceFiles() {
    $files = id(new FileFinder($this->root))
      ->withType('f')
      ->withSuffix('php')
      ->excludePath('*/.*')
      ->find();

    $paths = array();
    foreach ($files as $file) {
      $path = ltrim(Filesystem::readablePath($file, $this->root), '/');

      // Files at the root are the library's own init and map files.
      $is_library_file = (dirname($path) == '.');
      $is_extension = !strncmp($path, 'extensions/', strlen('extensions/'));
      if ($is_library_file || $is_extension) {
        continue;
      }

      $paths[] = $path;
    }

    return $paths;
  }

  /**
   * Find the classes, interfaces and top-level functions a file declares.
   *
   * Returns `class` as a map from each class or interface to its parent class
   * and interfaces, in declaration order, and `function` as a list.
   */
  private function findDeclarations($source) {
    $tokens = $this->getSignificantTokens($source);

    $classes = array();
    $functions = array();
    $brace_depth = 0;

    foreach ($tokens as $position => $token) {
      $previous = idx($tokens, $position - 1);
      $next = idx($tokens, $position + 1);

      if ($this->opensBrace($token)) {
        $brace_depth++;
      } else if ($token === '}') {
        $brace_depth--;
      } else if ($this->startsClassDeclaration($token, $previous)) {
        $classes[$next[1]] = $this->findParents($tokens, $position + 2);
      } else if ($this->isTokenType($token, T_FUNCTION) && !$brace_depth) {
        if ($this->isTokenType($next, T_STRING)) {
          $functions[] = $next[1];
        }
      }
    }

    return array(
      'class' => $classes,
      'function' => $functions,
    );
  }

  /**
   * Read the `extends` and `implements` names between a class name and the
   * class body.
   */
  private function findParents(array $tokens, $position) {
    $parents = array();
    $name = null;

    for (; $tokens[$position] !== '{'; $position++) {
      $token = $tokens[$position];
      if ($this->isTokenType($token, T_STRING) ||
          $this->isTokenType($token, T_NS_SEPARATOR)) {
        $name .= $token[1];
        continue;
      }

      if ($name !== null) {
        $parents[] = $name;
        $name = null;
      }
    }

    if ($name !== null) {
      $parents[] = $name;
    }

    return $parents;
  }

  private function getSignificantTokens($source) {
    $ignored_types = array(T_WHITESPACE, T_COMMENT, T_DOC_COMMENT);

    $tokens = array();
    foreach (token_get_all($source) as $token) {
      if (is_array($token) && in_array($token[0], $ignored_types)) {
        continue;
      }
      $tokens[] = $token;
    }

    return $tokens;
  }

  /**
   * The `class` keyword also appears in `Foo::class` and in `new class`.
   */
  private function startsClassDeclaration($token, $previous) {
    $is_declaration = $this->isTokenType($token, T_CLASS) ||
      $this->isTokenType($token, T_INTERFACE) ||
      $this->isTokenType($token, T_TRAIT);
    if (!$is_declaration) {
      return false;
    }

    return !$this->isTokenType($previous, T_DOUBLE_COLON) &&
      !$this->isTokenType($previous, T_NEW);
  }

  /**
   * Interpolations like `{$x}` and `${x}` in strings close with a plain `}`.
   */
  private function opensBrace($token) {
    return ($token === '{') ||
      $this->isTokenType($token, T_CURLY_OPEN) ||
      $this->isTokenType($token, T_DOLLAR_OPEN_CURLY_BRACES);
  }

  private function isTokenType($token, $type) {
    return is_array($token) && ($token[0] === $type);
  }

}
